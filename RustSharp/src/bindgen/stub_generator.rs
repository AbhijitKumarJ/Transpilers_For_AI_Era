//! Ambient `.d.rsharp` stub generator for `rsharp-bindgen`.
//!
//! Synthesizes C# ambient headers decorated with `[MapsTo]`, `[ParamType]`, `[Borrow]`,
//! and checked effects (`throws E`) from parsed Rust crate ASTs.

use std::collections::BTreeMap;

use crate::bindgen::crate_analyzer::RustCrateInfo;
use crate::bindgen::rs_ast::*;

pub struct StubGenerator;

impl StubGenerator {
    /// Generates the complete `.d.rsharp` file string for a crate.
    pub fn generate(crate_info: &RustCrateInfo, namespace_override: Option<&str>) -> String {
        let mut out = String::new();

        let ns_name = namespace_override
            .map(|s| s.to_string())
            .unwrap_or_else(|| to_pascal_case(&crate_info.name));

        // Header comments
        out.push_str(
            "// ============================================================================\n",
        );
        out.push_str(&format!(
            "// Ambient declarations auto-generated by rsharp-bindgen for crate '{}' v{}\n",
            crate_info.name, crate_info.version
        ));
        out.push_str(
            "// DO NOT EDIT DIRECTLY. Mapped compile-time stubs to native Rust Cargo APIs.\n",
        );
        out.push_str(
            "// ============================================================================\n\n",
        );

        // Assembly/crate dependency metadata
        out.push_str(&format!(
            "[assembly: CrateDependency(\"{}\", \"{}\")]\n\n",
            crate_info.name, crate_info.version
        ));

        // Namespace opening
        out.push_str(&format!("namespace {}\n{{\n", ns_name));

        // Group impl methods by target type name
        let mut impl_methods_by_type: BTreeMap<String, Vec<&RustFn>> = BTreeMap::new();
        for im in &crate_info.root_module.impls {
            for m in &im.methods {
                if m.is_pub {
                    impl_methods_by_type
                        .entry(im.target_type.clone())
                        .or_default()
                        .push(m);
                }
            }
        }

        // Emit Structs
        for st in &crate_info.root_module.structs {
            if !st.is_pub {
                continue;
            }
            let associated_methods = impl_methods_by_type.remove(&st.name).unwrap_or_default();
            Self::emit_struct(&mut out, &crate_info.name, st, &associated_methods, 4);
        }

        // Emit Enums
        for en in &crate_info.root_module.enums {
            if !en.is_pub {
                continue;
            }
            Self::emit_enum(&mut out, &crate_info.name, en, 4);
        }

        // Emit Traits
        for tr in &crate_info.root_module.traits {
            if !tr.is_pub {
                continue;
            }
            Self::emit_trait(&mut out, &crate_info.name, tr, 4);
        }

        // Emit standalone impl blocks for types not declared in this module (or primitives/foreign types)
        for (target_type, methods) in impl_methods_by_type {
            Self::emit_orphan_impl(&mut out, &crate_info.name, &target_type, &methods, 4);
        }

        // Emit Free Functions and Consts in a Module Static Class
        let pub_fns: Vec<&RustFn> = crate_info
            .root_module
            .functions
            .iter()
            .filter(|f| f.is_pub)
            .collect();
        let pub_consts: Vec<&RustConst> = crate_info
            .root_module
            .consts
            .iter()
            .filter(|c| c.is_pub)
            .collect();

        if !pub_fns.is_empty() || !pub_consts.is_empty() {
            let class_name = format!("{}Module", ns_name);
            out.push_str(&format!("    public static class {}\n    {{\n", class_name));

            for cn in pub_consts {
                Self::emit_const(&mut out, cn, 8);
            }

            for f in pub_fns {
                Self::emit_free_function(&mut out, &crate_info.name, f, 8);
            }

            out.push_str("    }\n\n");
        }

        // Emit Submodules as nested static classes or namespaces
        for sub in &crate_info.root_module.submodules {
            Self::emit_submodule(&mut out, &crate_info.name, sub, 4);
        }

        // Namespace closing
        out.push_str("}\n");

        out
    }

    fn emit_doc_comments(out: &mut String, docs: &[String], indent: usize) {
        let pad = " ".repeat(indent);
        for d in docs {
            out.push_str(&format!("{}/// {}\n", pad, d));
        }
    }

    fn emit_struct(
        out: &mut String,
        crate_name: &str,
        st: &RustStruct,
        methods: &[&RustFn],
        indent: usize,
    ) {
        let pad = " ".repeat(indent);
        Self::emit_doc_comments(out, &st.doc_comments, indent);

        out.push_str(&format!(
            "{}[MapsTo(\"{}::{}\")]\n",
            pad, crate_name, st.name
        ));

        let has_mut_methods = methods
            .iter()
            .any(|m| m.self_receiver == Some(RustSelfReceiver::MutRef));

        let archetype_kw = if has_mut_methods { "class" } else { "struct" };
        let generics_str = if st.generics.is_empty() {
            String::new()
        } else {
            format!("<{}>", st.generics.join(", "))
        };

        out.push_str(&format!(
            "{}public {} {}{}\n{}{{\n",
            pad, archetype_kw, st.name, generics_str, pad
        ));

        // Fields
        for field in &st.fields {
            if !field.is_pub {
                continue;
            }
            Self::emit_doc_comments(out, &field.doc_comments, indent + 4);
            let field_pad = " ".repeat(indent + 4);
            let csharp_type = rust_type_to_csharp(&field.ty);
            let field_name = to_pascal_case(&field.name);
            out.push_str(&format!(
                "{}[MapsTo(\"{}\")]\n{}public {} {};\n",
                field_pad, field.name, field_pad, csharp_type, field_name
            ));
        }

        // Methods
        for m in methods {
            Self::emit_method(out, &st.name, m, indent + 4);
        }

        out.push_str(&format!("{}}}\n\n", pad));
    }

    fn emit_enum(out: &mut String, crate_name: &str, en: &RustEnum, indent: usize) {
        let pad = " ".repeat(indent);
        Self::emit_doc_comments(out, &en.doc_comments, indent);

        out.push_str(&format!(
            "{}[MapsTo(\"{}::{}\")]\n",
            pad, crate_name, en.name
        ));
        out.push_str(&format!("{}public enum {}\n{}{{\n", pad, en.name, pad));

        let inner_pad = " ".repeat(indent + 4);
        for v in &en.variants {
            Self::emit_doc_comments(out, &v.doc_comments, indent + 4);
            out.push_str(&format!("{}{},\n", inner_pad, v.name));
        }

        out.push_str(&format!("{}}}\n\n", pad));
    }

    fn emit_trait(out: &mut String, crate_name: &str, tr: &RustTrait, indent: usize) {
        let pad = " ".repeat(indent);
        Self::emit_doc_comments(out, &tr.doc_comments, indent);

        let interface_name = if tr.name.starts_with('I') {
            tr.name.clone()
        } else {
            format!("I{}", tr.name)
        };

        out.push_str(&format!(
            "{}[MapsTo(\"{}::{}\")]\n",
            pad, crate_name, tr.name
        ));
        out.push_str(&format!(
            "{}public extensible interface {}\n{}{{\n",
            pad, interface_name, pad
        ));

        for m in &tr.methods {
            Self::emit_method(out, &interface_name, m, indent + 4);
        }

        out.push_str(&format!("{}}}\n\n", pad));
    }

    fn emit_orphan_impl(
        out: &mut String,
        crate_name: &str,
        target_type: &str,
        methods: &[&RustFn],
        indent: usize,
    ) {
        let pad = " ".repeat(indent);
        let class_name = format!("{}Extensions", target_type);
        out.push_str(&format!(
            "{}[MapsTo(\"{}::{}\")]\n",
            pad, crate_name, target_type
        ));
        out.push_str(&format!(
            "{}public static class {}\n{}{{\n",
            pad, class_name, pad
        ));

        for m in methods {
            Self::emit_method(out, target_type, m, indent + 4);
        }

        out.push_str(&format!("{}}}\n\n", pad));
    }

    fn emit_method(out: &mut String, type_name: &str, m: &RustFn, indent: usize) {
        let pad = " ".repeat(indent);
        Self::emit_doc_comments(out, &m.doc_comments, indent);

        let is_constructor = m.name == "new"
            && matches!(&m.return_type, RustType::SelfType | RustType::Named { .. });
        let is_static = m.self_receiver.is_none();

        let (ret_type_str, throws_str) = decompose_return_type(&m.return_type, type_name);

        out.push_str(&format!("{}[MapsTo(\"{}\")]\n", pad, m.name));

        if let Some(RustSelfReceiver::MutRef) = &m.self_receiver {
            out.push_str(&format!("{}[Borrow(BorrowKind.MutBorrow)]\n", pad));
        }

        let static_mod = if is_static && !is_constructor {
            "static "
        } else {
            ""
        };
        let method_name = if is_constructor {
            type_name.to_string()
        } else {
            to_pascal_case(&m.name)
        };

        let params_str = format_parameters(&m.params);

        if is_constructor {
            out.push_str(&format!(
                "{}public {}({}){};\n",
                pad, method_name, params_str, throws_str
            ));
        } else {
            out.push_str(&format!(
                "{}public {}{} {}({}){};\n",
                pad, static_mod, ret_type_str, method_name, params_str, throws_str
            ));
        }
    }

    fn emit_free_function(out: &mut String, crate_name: &str, f: &RustFn, indent: usize) {
        let pad = " ".repeat(indent);
        Self::emit_doc_comments(out, &f.doc_comments, indent);

        let (ret_type_str, throws_str) = decompose_return_type(&f.return_type, "");
        let params_str = format_parameters(&f.params);
        let fn_pascal = to_pascal_case(&f.name);

        out.push_str(&format!(
            "{}[MapsTo(\"{}::{}\")]\n",
            pad, crate_name, f.name
        ));
        out.push_str(&format!(
            "{}public static {} {}({}){};\n",
            pad, ret_type_str, fn_pascal, params_str, throws_str
        ));
    }

    fn emit_const(out: &mut String, c: &RustConst, indent: usize) {
        let pad = " ".repeat(indent);
        Self::emit_doc_comments(out, &c.doc_comments, indent);

        let ty_str = rust_type_to_csharp(&c.ty);
        let const_pascal = to_pascal_case(&c.name);
        out.push_str(&format!(
            "{}public const {} {} = {};\n",
            pad, ty_str, const_pascal, c.value
        ));
    }

    fn emit_submodule(out: &mut String, crate_name: &str, sub: &RustModule, indent: usize) {
        let pad = " ".repeat(indent);
        let mod_pascal = to_pascal_case(&sub.name);
        out.push_str(&format!(
            "{}public static class {}\n{}{{\n",
            pad, mod_pascal, pad
        ));

        // Group submodule impl methods
        let mut impl_methods_by_type: BTreeMap<String, Vec<&RustFn>> = BTreeMap::new();
        for im in &sub.impls {
            for m in &im.methods {
                if m.is_pub {
                    impl_methods_by_type
                        .entry(im.target_type.clone())
                        .or_default()
                        .push(m);
                }
            }
        }

        let sub_crate_path = format!("{}::{}", crate_name, sub.name);

        for st in &sub.structs {
            if st.is_pub {
                let methods = impl_methods_by_type.remove(&st.name).unwrap_or_default();
                Self::emit_struct(out, &sub_crate_path, st, &methods, indent + 4);
            }
        }

        for en in &sub.enums {
            if en.is_pub {
                Self::emit_enum(out, &sub_crate_path, en, indent + 4);
            }
        }

        for tr in &sub.traits {
            if tr.is_pub {
                Self::emit_trait(out, &sub_crate_path, tr, indent + 4);
            }
        }

        for cn in &sub.consts {
            if cn.is_pub {
                Self::emit_const(out, cn, indent + 4);
            }
        }

        for f in &sub.functions {
            if f.is_pub {
                Self::emit_free_function(out, &sub_crate_path, f, indent + 4);
            }
        }

        out.push_str(&format!("{}}}\n\n", pad));
    }
}

fn decompose_return_type(ty: &RustType, enclosing_type: &str) -> (String, String) {
    match ty {
        RustType::Named { path, generic_args }
            if path.last().map(|s| s.as_str()) == Some("Result") =>
        {
            let ok_type = generic_args
                .first()
                .map(rust_type_to_csharp)
                .unwrap_or_else(|| "void".to_string());
            let err_type = generic_args
                .get(1)
                .map(rust_type_to_csharp)
                .unwrap_or_else(|| "Exception".to_string());
            (ok_type, format!(" throws {}", err_type))
        }
        RustType::SelfType => (enclosing_type.to_string(), String::new()),
        other => (rust_type_to_csharp(other), String::new()),
    }
}

fn format_parameters(params: &[RustParam]) -> String {
    let mut parts = Vec::new();
    for p in params {
        let (param_attr, ty_str, by_ref) = match &p.ty {
            RustType::Reference {
                is_mut: true,
                inner,
            } => ("[ParamType(\"mut\")] ", rust_type_to_csharp(inner), "ref "),
            RustType::Reference {
                is_mut: false,
                inner,
            } => {
                if inner.is_str() {
                    ("", "string".to_string(), "")
                } else {
                    ("[ParamType(\"ref\")] ", rust_type_to_csharp(inner), "")
                }
            }
            other => ("", rust_type_to_csharp(other), ""),
        };
        parts.push(format!("{}{}{} {}", param_attr, by_ref, ty_str, p.name));
    }
    parts.join(", ")
}

pub fn rust_type_to_csharp(ty: &RustType) -> String {
    match ty {
        RustType::Primitive(p) => match p.as_str() {
            "i8" => "sbyte".to_string(),
            "u8" => "byte".to_string(),
            "i16" => "short".to_string(),
            "u16" => "ushort".to_string(),
            "i32" => "int".to_string(),
            "u32" => "uint".to_string(),
            "i64" => "long".to_string(),
            "u64" => "ulong".to_string(),
            "isize" => "nint".to_string(),
            "usize" => "nuint".to_string(),
            "f32" => "float".to_string(),
            "f64" => "double".to_string(),
            "bool" => "bool".to_string(),
            "char" => "char".to_string(),
            _ => p.clone(),
        },
        RustType::Named { path, generic_args } => {
            let last = path.last().map(|s| s.as_str()).unwrap_or("");
            match last {
                "String" => "string".to_string(),
                "str" => "string".to_string(),
                "Vec" => {
                    let arg = generic_args
                        .first()
                        .map(rust_type_to_csharp)
                        .unwrap_or_else(|| "object".to_string());
                    format!("List<{}>", arg)
                }
                "Option" => {
                    let arg = generic_args
                        .first()
                        .map(rust_type_to_csharp)
                        .unwrap_or_else(|| "object".to_string());
                    format!("{}?", arg)
                }
                "HashMap" | "BTreeMap" => {
                    let k = generic_args
                        .first()
                        .map(rust_type_to_csharp)
                        .unwrap_or_else(|| "object".to_string());
                    let v = generic_args
                        .get(1)
                        .map(rust_type_to_csharp)
                        .unwrap_or_else(|| "object".to_string());
                    format!("Dictionary<{}, {}>", k, v)
                }
                "HashSet" | "BTreeSet" => {
                    let item = generic_args
                        .first()
                        .map(rust_type_to_csharp)
                        .unwrap_or_else(|| "object".to_string());
                    format!("HashSet<{}>", item)
                }
                "Result" => {
                    let ok = generic_args
                        .first()
                        .map(rust_type_to_csharp)
                        .unwrap_or_else(|| "object".to_string());
                    let err = generic_args
                        .get(1)
                        .map(rust_type_to_csharp)
                        .unwrap_or_else(|| "object".to_string());
                    format!("Result<{}, {}>", ok, err)
                }
                _ => {
                    if generic_args.is_empty() {
                        last.to_string()
                    } else {
                        let args: Vec<String> =
                            generic_args.iter().map(rust_type_to_csharp).collect();
                        format!("{}<{}>", last, args.join(", "))
                    }
                }
            }
        }
        RustType::Reference { inner, .. } => {
            if inner.is_str() {
                "string".to_string()
            } else {
                rust_type_to_csharp(inner)
            }
        }
        RustType::Slice { inner, .. } => {
            let inner_cs = rust_type_to_csharp(inner);
            format!("List<{}>", inner_cs)
        }
        RustType::Tuple(elems) => {
            if elems.is_empty() {
                "void".to_string()
            } else {
                let parts: Vec<String> = elems.iter().map(rust_type_to_csharp).collect();
                format!("({})", parts.join(", "))
            }
        }
        RustType::Unit => "void".to_string(),
        RustType::SelfType => "Self".to_string(),
    }
}

pub fn to_pascal_case(s: &str) -> String {
    let mut result = String::new();
    let mut capitalize = true;
    for c in s.chars() {
        if c == '_' || c == '-' {
            capitalize = true;
        } else if capitalize {
            result.extend(c.to_uppercase());
            capitalize = false;
        } else {
            result.extend(c.to_lowercase());
        }
    }
    result
}
