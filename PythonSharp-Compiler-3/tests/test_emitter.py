from __future__ import annotations

import json
from pathlib import Path

from psc import compile_sources
from psc.codegen import ArtifactEmitter

STDLIB = Path("stdlib/PythonSharp.Core.d.ps")


def test_emitter_writes_packages_pyc_files_and_deterministic_manifest(tmp_path: Path) -> None:
    source = """
    namespace Sample.Domain;

    public record Item(int Id, string Name);

    public class Catalog
    {
        private readonly Dict<int, Item> _items = new Dict<int, Item>();

        public void Add(Item item) => _items[item.Id] = item;

        public List<int> Ids()
        {
            return _items.Values().Select(item => item.Id).ToList();
        }
    }
    """
    artifacts, diagnostics = compile_sources(
        sources={"Sample/Catalog.ps": source},
        out_dir=tmp_path / "dist",
        stdlib_source=STDLIB.read_text(encoding="utf-8"),
        assembly_name="Sample",
        emit_pyc=True,
    )
    assert not diagnostics.has_errors(), diagnostics.format_all()
    assert len(artifacts) == 1

    artifact = artifacts[0]
    assert artifact.module_rel_path == "sample/domain.py"
    assert artifact.py_path.exists()
    assert artifact.pyc_path is not None and artifact.pyc_path.exists()
    assert artifact.pycache_pyc_path is not None and artifact.pycache_pyc_path.exists()
    assert artifact.py_source.startswith("# Auto-generated by PythonSharp (psc)")
    assert (tmp_path / "dist" / "sample" / "__init__.py").exists()

    loaded = ArtifactEmitter.load_code_from_pyc(artifact.pyc_path)
    assert loaded.co_filename == "Sample/Catalog.ps"

    manifest_path = tmp_path / "dist" / "psc-manifest.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    assert manifest["schema_version"] == 1
    assert manifest["modules"][0]["module"] == "sample/domain.py"
    assert manifest["modules"][0]["primary_ps"] == "Sample/Catalog.ps"
    assert manifest["modules"][0]["pyc"] == "sample/domain.pyc"
    assert str(tmp_path) not in manifest_path.read_text(encoding="utf-8")
