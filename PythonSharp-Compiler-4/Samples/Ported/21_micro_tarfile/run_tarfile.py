#!/usr/bin/env python3
"""
Test runner for Ported 21_micro_tarfile (POSIX USTAR binary tarball parser/generator in PythonSharp).
Builds the project with `psc` and validates in-memory archiving, byte manipulation, and standard library tarfile interop.
"""
from __future__ import annotations

import io
import shutil
import subprocess
import sys
import tarfile
from pathlib import Path


def main() -> int:
    proj_dir = Path(__file__).resolve().parent
    dist_dir = proj_dir / "dist"

    print("=== Step 1: Building MicroTarFile via `psc build` ===")
    psc_bin = shutil.which("psc")
    if psc_bin:
        cmd = [psc_bin, "build", str(proj_dir)]
    else:
        cmd = [sys.executable, "-m", "psc.cli", "build", str(proj_dir)]

    res = subprocess.run(cmd, capture_output=True, text=True)
    if res.returncode != 0:
        print(f"Build failed:\n{res.stderr}\n{res.stdout}", file=sys.stderr)
        return 1
    print(res.stdout.strip())

    print("\n=== Step 2: Testing Ported MicroTarFile Functionality ===")
    sys.path.insert(0, str(dist_dir))

    try:
        from micro_tar_file import MicroTarArchive, TarEntry, TarHeader
    except ImportError as e:
        print(f"Failed to import micro_tar_file: {e}", file=sys.stderr)
        return 1

    # 1. Test Header Generation & Checksum
    content1 = b"Hello from PythonSharp TAR file!"
    header = TarHeader.create_header("file1.txt", len(content1), 0o644)
    assert len(header) == 512
    assert header[:9].decode("ascii") == "file1.txt"
    assert header[257:262].decode("ascii") == "ustar"
    print("[PASS] 512-byte USTAR Header generation & Checksum verified")

    # 2. In-Memory Archive Creation
    content2 = b'{"version": 2, "description": "MicroTarFile config", "enabled": true}'
    content3 = b"#!/usr/bin/env python3\nprint('Hello from embedded script!')\n"

    entries = [
        TarEntry("docs/readme.txt", len(content1), 0o644, content1),
        TarEntry("settings/config.json", len(content2), 0o600, content2),
        TarEntry("bin/run.sh", len(content3), 0o755, content3),
    ]

    tar_bytes = MicroTarArchive.create_archive(entries)
    assert len(tar_bytes) % 512 == 0
    # Expected: 3 headers (3 * 512) + 3 padded payloads (3 * 512) + 2 eof blocks (2 * 512) = 8 * 512 = 4096 bytes
    assert len(tar_bytes) == 4096
    print(f"[PASS] Archive created: {len(tar_bytes)} bytes across 3 entries + EOF markers")

    # 3. Reading Back with MicroTarArchive
    read_entries = MicroTarArchive.read_archive(tar_bytes)
    assert len(read_entries) == 3
    print(f"[PASS] MicroTarArchive.read_archive extracted {len(read_entries)} entries")

    e1 = MicroTarArchive.find_entry(read_entries, "docs/readme.txt")
    assert e1 is not None
    assert e1.name == "docs/readme.txt"
    assert e1.size == len(content1)
    assert e1.mode == 0o644
    assert e1.content == content1
    print(f"[PASS] Verified entry 1: {e1.name} (size={e1.size}, mode={oct(e1.mode)})")

    e2 = MicroTarArchive.find_entry(read_entries, "settings/config.json")
    assert e2 is not None
    assert e2.name == "settings/config.json"
    assert e2.size == len(content2)
    assert e2.mode == 0o600
    assert e2.content == content2
    print(f"[PASS] Verified entry 2: {e2.name} (size={e2.size}, mode={oct(e2.mode)})")

    e3 = MicroTarArchive.find_entry(read_entries, "bin/run.sh")
    assert e3 is not None
    assert e3.name == "bin/run.sh"
    assert e3.size == len(content3)
    assert e3.mode == 0o755
    assert e3.content == content3
    print(f"[PASS] Verified entry 3: {e3.name} (size={e3.size}, mode={oct(e3.mode)})")

    # 4. Standard Library `tarfile` Compatibility
    with tarfile.open(fileobj=io.BytesIO(tar_bytes), mode="r") as tf:
        members = tf.getmembers()
        assert len(members) == 3
        member_names = [m.name for m in members]
        assert member_names == ["docs/readme.txt", "settings/config.json", "bin/run.sh"]

        extracted1 = tf.extractfile("docs/readme.txt").read()
        assert extracted1 == content1

        extracted2 = tf.extractfile("settings/config.json").read()
        assert extracted2 == content2

        extracted3 = tf.extractfile("bin/run.sh").read()
        assert extracted3 == content3
    print("[PASS] Python standard library `tarfile` extracted MicroTarArchive output with 100% parity")

    # 5. Reverse Compatibility: MicroTarArchive Reading Standard Python tarfile Output
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w") as tf:
        ti = tarfile.TarInfo("external_package/manifest.txt")
        payload = b"Generated by standard Python tarfile module."
        ti.size = len(payload)
        ti.mode = 0o644
        tf.addfile(ti, io.BytesIO(payload))

    py_tar_bytes = buf.getvalue()
    extracted_from_py = MicroTarArchive.read_archive(py_tar_bytes)
    assert len(extracted_from_py) == 1
    assert extracted_from_py[0].name == "external_package/manifest.txt"
    assert extracted_from_py[0].size == len(payload)
    assert extracted_from_py[0].content == payload
    print("[PASS] MicroTarArchive successfully read archive generated by Python's standard `tarfile` module")

    print("\nAll 21_micro_tarfile verification checks succeeded with 0 errors!")
    return 0


if __name__ == "__main__":
    sys.exit(main())

